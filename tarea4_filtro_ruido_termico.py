"""Módulo para el filtrado de ruido térmico en calderas industriales.

Optimizado bajo los estándares de estilo PEP 8 y complejidad lineal O(N).
"""

TEMPERATURAS_CALDERA = [110.5, 112.3, 115.8, 111.2, 118.4] * 2000


def filtrar_ruido_termico() -> list[float]:
    """Calcula el promedio móvil acumulado de las temperaturas de la caldera.

    Elimina el bucle anidado para optimizar el rendimiento del procesador.
    """
    temperaturas_filtradas = []
    suma_acumulada = 0.0

    for indice, temperatura in enumerate(TEMPERATURAS_CALDERA, start=1):
        suma_acumulada += temperatura
        promedio = suma_acumulada / indice
        temperaturas_filtradas.append(promedio)

    return temperaturas_filtradas


